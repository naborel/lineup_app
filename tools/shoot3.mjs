// Dev helper: phone-sized screenshots. node tools/shoot3.mjs <outdir>
import { chromium } from 'playwright';
import path from 'path';
const out = process.argv[2];
const file = 'file://' + path.resolve('Lineup.html');
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
p.on('console', m => { if (m.type() === 'error') errs.push('CONSOLE ' + m.text()); });
await p.goto(file);
await p.waitForSelector('.page-head'); await p.waitForTimeout(700);
await p.tap('.split-empty .btn'); await p.waitForTimeout(1300);
await p.screenshot({ path: `${out}/m1-split.png` });
await p.evaluate(() => window.scrollTo(0, 620)); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/m2-split-days.png` });
await p.evaluate(() => window.scrollTo(0, 0)); await p.waitForTimeout(300);
const box = await p.evaluate(() => { const el = document.querySelector('.mz[data-z="lats"]'); const r = el.getBoundingClientRect(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; });
await p.touchscreen.tap(box.x, box.y); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/m3-picker.png` });
await p.touchscreen.tap(195, 60); await p.waitForTimeout(500);
await p.evaluate(() => { location.hash = 'track'; }); await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/m4-track.png` });
await p.tap('.tc-id'); await p.waitForTimeout(1000);
await p.screenshot({ path: `${out}/m5-sheet.png` });
await p.tap('.sheet .close'); await p.waitForTimeout(400);
await p.evaluate(() => { location.hash = 'table'; }); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/m6-table.png` });
await p.evaluate(() => { location.hash = 'favorites'; }); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/m7-favorites.png` });
const overflow = await p.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
console.log('horizontal overflow px:', overflow);
console.log(errs.length ? errs.slice(0, 12).join('\n') : 'no errors');
await b.close();
